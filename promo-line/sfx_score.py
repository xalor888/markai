#!/usr/bin/env python3
"""sfx_score.py — 「一条线」(MarkAI 15s) 的声音，写在 sfx_palette 上。

五种材质一个房间：air（线的呼吸/飞行）、wood（键/点击）、glass（点亮/对勾）、
sub（落地/收尾）、bubble（弹出）。rest 段（9.95–11.62）刻意近无声——静是让
burst 落地的东西。事件数少于节拍数：盘圈只给一声 wobble，扫描只在每两行给一个 tick。
run:  venv-python3 sfx_score.py  →  sfx.wav (48 kHz, peak −8 dBFS)
"""
import os, sys
sys.path.insert(0, "/Users/xalor/.workbuddy/skills/onetake/scripts")
from sfx_palette import Score, air, glass, wood, sub, bubble, wobble, pan_of
import numpy as np

rng = np.random.default_rng(21)
s = Score(dur=15.0, T60=1.1)
place = s.place

# 1 · 开场：黑场里一条线的呼吸 —— sub 低鸣 + 极轻的空气
place(sub(56, 1.1), 0.12, 0.20, 0.0, 0.35)
place(air(1.0, 120, 900, 1.2, 0.4), 0.15, 0.10, 0.0, 0.30)

# 2 · 线竖起滑入输入条（1.30）：一声很轻的上扬空气
place(air(0.42, 300, 1800, 1.2, 0.5), 1.32, 0.20, 0.0, 0.35)

# 3 · 打字（1.58–2.27，9 字 cps15）：闷木键声，约三分之二概率、力度不一
TXT = '帮我清理失效书签'
for i, ch in enumerate(TXT):
    if rng.uniform() < 0.30:
        continue
    place(wood(165 + rng.uniform(-18, 18), 0.09), 1.58 + i / 15 + rng.uniform(0, 0.004),
          0.09 * rng.uniform(0.7, 1.3), -0.04, 0.15)

# 4 · send（2.70）：气泡被送走的一口气 + 轻弹
place(air(0.34, 1500, 320, 1.3), 2.72, 0.20, 0.0, 0.40)
place(bubble(430, 0.22), 2.76, 0.22, 0.05, 0.30)

# 5 · 线从上方落下（2.98–3.62）：下坠的空气 + 落地（sub + 短木）
place(air(0.55, 220, 2600, 1.1, 0.4), 2.98, 0.30, 0.0, 0.45)
place(sub(64, 0.42), 3.62, 0.34, 0.0, 0.30)
place(wood(210, 0.07), 3.62, 0.24, 0.0, 0.20)

# 6 · 扫描（3.70–6.05）：每两行一枚玻璃 tick，音阶上行；死链出现时一声低玻璃（下行小三度）
for t, f in ((3.86, 523), (4.45, 659), (5.03, 784), (5.62, 988), (5.95, 1175)):
    place(glass(f, 0.5, 0.65), t, 0.13, 0.0, 0.40)
for t in (4.16, 4.75, 5.90):
    place(glass(311, 1.0, 0.45), t, 0.15, 0.08, 0.50)   # 死链：暗一点的玻璃

# 7 · 盘圈（6.35–7.02）：一声低鸣 wobble —— 线在收拢自己
place(wobble(140, 0.6), 6.40, 0.34, 0.10, 0.35)
place(air(0.5, 400, 2200, 1.4, 0.3), 6.35, 0.16, 0.05, 0.40, pan_to=0.35)

# 8 · 卡片弹出（7.06）：木头落地 + sub
place(wood(140, 0.10), 7.10, 0.30, pan_of(1175), 0.25)
place(sub(72, 0.3), 7.10, 0.22, 0.0, 0.30)
place(bubble(520, 0.2), 7.12, 0.18, pan_of(1175), 0.30)

# 9 · 光标点击「删除」（8.32）：down/up 两声木键
place(wood(235, 0.08), 8.32, 0.30, pan_of(1337), 0.20)
place(wood(185, 0.07), 8.40, 0.20, pan_of(1337), 0.20)

# 10 · 对勾（8.88）：玻璃两音（成功和弦，纯五度）
place(glass(1046, 0.9, 0.5), 8.92, 0.17, 0.0, 0.55)
place(glass(1568, 0.9, 0.4), 8.95, 0.12, 0.05, 0.55)

# 11 · burst（9.42/9.60/9.78）：三声 sub+wood，音高下行、渐弱
for t, g, f in ((9.44, 0.30, 96), (9.62, 0.24, 82), (9.80, 0.18, 68)):
    place(sub(f, 0.3), t, g, 0.0, 0.30)
    place(wood(190 - (9.44 - t) * 40, 0.06), t, g * 0.7, 0.0, 0.20)

# 12 · rest（9.95–11.62）：近无声。只有一点房间的空气在很远的地方
place(air(1.4, 90, 400, 1.0, 0.3), 10.2, 0.05, 0.0, 0.25)

# 13 · 飞线（11.65–12.85）：一口气从左下扫到右上（pan 跟着走）
place(air(1.05, 300, 2400, 1.3, 0.5), 11.67, 0.34, -0.05, 0.50, pan_to=0.45)

# 14 · 字母落下（12.02–12.30）：三声木 tick（M、A、I 的落点）
for t, f in ((12.06, 300), (12.17, 260), (12.28, 220)):
    place(wood(f, 0.07), t, 0.16, 0.0, 0.20)

# 15 · 句号点落定（12.85）：一枚很轻的玻璃；end 收在 sub 里
place(glass(1318, 0.8, 0.4), 12.86, 0.14, 0.10, 0.45)
place(sub(54, 1.6), 12.98, 0.16, 0.0, 0.40)

s.write('sfx.wav')
print('sfx.wav written · 48 kHz · peak −8 dBFS · 15.0 s')
